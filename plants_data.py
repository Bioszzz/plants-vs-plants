    def can_pay(self, player):
        """代价是否付得起。耗生命不允许把自己耗死【待确认】"""
        if player.seeds < self.cost_seed:
            return False
        if self.cost_hp > 0 and player.hp - self.cost_hp <= 0:
            return False
        return True

    def pay(self, player):
        player.seeds -= self.cost_seed
        player.hp -= self.cost_hp

    def charge_line(self, n):
        """【v0.17】充能 n 颗种子之后的说明。
        引擎的战报、网页 / tkinter / 命令行界面的询问框，一律调这一个方法 ——
        每株充能植物的话术都不一样，不许再写死某一株的公式（人参果没有攻击力）。"""
        t = self.charge_text
        if t is None:
            return "防御力%d" % n                    # 兜底：只改防御
        if callable(t):
            return t(n)
        return t.format(atk=n + 1, fang=n, seg=n, name=self.name)

